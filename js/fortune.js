// ---- 今日の運勢 ----
function kyouUranai(birth) {
  const r = rng(seedFrom(birth + "|" + todayKey()));
  const score = 60 + Math.floor(r() * 41); // 60-100
  const starsN = score >= 92 ? 5 : score >= 82 ? 4 : score >= 72 ? 3 : 2;
  return {
    score: score,
    stars: "★".repeat(starsN) + "☆".repeat(5 - starsN),
    main: FORTUNE_MAIN[Math.floor(r() * FORTUNE_MAIN.length)],
    color: LUCKY_COLOR[Math.floor(r() * LUCKY_COLOR.length)],
    item: LUCKY_ITEM[Math.floor(r() * LUCKY_ITEM.length)],
  };
}

